    private void bsupprimerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bsupprimerActionPerformed
        if (tutilisateur.getSelectedRowCount() == 1) {
            if (JOptionPane.showConfirmDialog(this, "Voulez vous vraiment supprimer l'utisateur", "confirmation", JOptionPane.YES_NO_OPTION) == JOptionPane.YES_OPTION) {
                try {
                    ps = c.connexionBdd().prepareStatement("delete from utilisateurs where nom_utilisateur=?");
                    ps.setString(1, tutilisateur.getValueAt(tutilisateur.getSelectedRow(), 0) + "");
                    ps.executeUpdate();
                    JOptionPane.showMessageDialog(this, "suppression faite avec succées");
                    actualiser();
                } catch (SQLException ex) {
                    Logger.getLogger(Paramètre.class.getName()).log(Level.SEVERE, null, ex);
                }
            }
        }
    }//GEN-LAST:event_bsupprimerActionPerformed

