    public static void actualiser() {
        dft.setRowCount(0);
        dft.setColumnCount(0);
        try {
            dft.addColumn("nom_utilisateur");
            dft.addColumn("type_utilisateur");
            dft.addColumn("mdp");
            dft.addColumn("nom");
            dft.addColumn("prénom");

            ps = c.connexionBdd().prepareStatement("select * from utilisateurs");
            rs = ps.executeQuery();
            while (rs.next()) {
                dft.addRow(new Object[]{
                    rs.getString("nom_utilisateur"),
                    rs.getString("type_utilisateur"),
                    rs.getString("mdp"),
                    rs.getString("nom"),
                    rs.getString("prénom")}
                );
            }
            tutilisateur.setModel(dft);
        } catch (SQLException ex) {
            Logger.getLogger(Paramètre.class
                    .getName()).log(Level.SEVERE, null, ex);
        }
    }

