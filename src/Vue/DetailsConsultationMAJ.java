    private void bsauvgarderActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bsauvgarderActionPerformed
        if (tnom.getText().isEmpty()|| tprenom1.getText().isEmpty() || jdate.getDate() == null || tmotif.getText().isEmpty()
                || ttaille.getText().isEmpty() || tpoids.getText().isEmpty() || ttempérature.getText().isEmpty() || tfrequence.getText().isEmpty()
                || tglycemie.getText().isEmpty() || tpression.getText().isEmpty() || timc.getText().isEmpty() || tdecision.getText().isEmpty()
                || tobservation.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Veuillez renseigner tout les champs !");
        } else if (JOptionPane.showConfirmDialog(this, "Voullez vous vraiment modifier?",
                "Confirmation de modification",
                JOptionPane.YES_NO_OPTION) == JOptionPane.YES_OPTION) {
            try {
                String idmed = "";
                ps = c.connexionBdd().prepareStatement("select nom_utilisateur from utilisateurs where nom=? and prénom=? and type_utilisateur='Médecin' ");
                ps.setString(1, tnom.getText());
                ps.setString(2, tprenom1.getText());
                rs = ps.executeQuery();
                while (rs.next()) {
                    idmed = rs.getString("nom_utilisateur");
                }
                if (idmed.equals("")) {
                    JOptionPane.showMessageDialog(this, "Le médecin n'existe pas !!");
                } else {
                    ps = c.connexionBdd().prepareStatement("update consultation set date_cons=? ,motif=? , taille=? ,poids=?, température=? ,fréquence_cardiaque=? ,glycémie=? ,pression_artérielle=? ,imc=? ,imcdec=?,observation=?,medecin_id=? where consultation_id=?");
                    SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
                    String daten = sdf.format(jdate.getDate());
                    ps.setString(1, daten);
                    ps.setString(2, tmotif.getText());
                    ps.setString(3, ttaille.getText());
                    ps.setString(4, tpoids.getText());
                    ps.setString(5, ttempérature.getText());
                    ps.setString(6, tfrequence.getText());
                    ps.setString(7, tglycemie.getText());
                    ps.setString(8, tpression.getText());
                    ps.setString(9, timc.getText());
                    ps.setString(10, tdecision.getText());
                    ps.setString(11, tobservation.getText());
                    ps.setString(12, idmed);
                    ps.setString(13, lnumcons.getText());
                    ps.executeUpdate();
                    JOptionPane.showMessageDialog(this, "Mise a jours faite avec succés");
                    DetailsPatient.actualiserc();
                    dispose();
                }

            } catch (SQLException ex) {
                Logger.getLogger(DetailsConsultationMAJ.class.getName()).log(Level.SEVERE, null, ex);
            }
        }
    }//GEN-LAST:event_bsauvgarderActionPerformed

