    public void Actualiser() {
        dft.setRowCount(0);
        dft.setColumnCount(0);
        try {
            dft.addColumn("ID");
            dft.addColumn("Médicament");
            dft.addColumn("Famille");
            dft.addColumn("Forme");
            dft.addColumn("Dosage");
            dft.addColumn("Posologie");
            dft.addColumn("Quantité");

            ps = c.connexionBdd().prepareStatement("select * from medicament where ordonnance_id= ?");
            ps.setString(1, lordonance.getText());
            rs = ps.executeQuery();
            while (rs.next()) {
                dft.addRow(new Object[]{
                    rs.getString("medicament_id"),
                    rs.getString("nom_med"),
                    rs.getString("famille_med"),
                    rs.getString("forme"),
                    rs.getString("dosage"),
                    rs.getString("posologie_usuelle"),
                    rs.getString("qte_med")
                }
                );
            }
            tmedicament.setModel(dft);
        } catch (SQLException ex) {
            Logger.getLogger(OrdonnanceMAJJ.class
                    .getName()).log(Level.SEVERE, null, ex);
        }
    }

