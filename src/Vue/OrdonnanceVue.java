    private void bimprimerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bimprimerActionPerformed
        if (Médecin.prv.charAt(19) == '1') {
            try {
                Class.forName("com.mysql.jdbc.Driver");
                Connection con = DriverManager.getConnection("jdbc:mysql://localhost:3306/gestion_cabinet_medical", "root", "");
                JasperDesign jdesing = JRXmlLoader.load("C:\\Users\\azus\\Documents\\NetBeansProjects\\gestion d'une cabinet medicale V7\\src\\EtatImpression\\FicheOrdonnance1.jrxml");
                String query = "Select ordonnance.* , medicament.*, utilisateurs.nom as nom ,patient.nom_pat,patient.prénom_pat,patient.date_naissance , medecin.specialite from ordonnance left join medicament on (medicament.ordonnance_id=ordonnance.ordonnance_id) left join patient on (patient.matricule_pat=ordonnance.matricule_pat) LEFT join medecin on (ordonnance.medecin_id=medecin.nom_utilisateur) left join utilisateurs on (medecin.nom_utilisateur=utilisateurs.nom_utilisateur) where ordonnance.ordonnance_id='" + lordonance.getText() + "'";
                JRDesignQuery updateQuery = new JRDesignQuery();
                updateQuery.setText(query);
                jdesing.setQuery(updateQuery);
                JasperReport jreport = JasperCompileManager.compileReport(jdesing);
                JasperPrint jprint = JasperFillManager.fillReport(jreport, null, con);
                
                JasperViewer.viewReport(jprint);
                
            } catch (ClassNotFoundException | SQLException | JRException ex) {
                Logger.getLogger(OrdonnanceVue.class.getName()).log(Level.SEVERE, null, ex);
            }
        } else {
            JOptionPane.showMessageDialog(this, "Vous disposer pas de ce privilége !");
        }
    }//GEN-LAST:event_bimprimerActionPerformed

