    private void bconnecterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bconnecterActionPerformed
        boolean tr = false;
        ConnectUtilisateur cu = new ConnectUtilisateur();
        try {
            while (cu.rs.next()) {
                if ((tusername.getText().equals(cu.rs.getString("nom_utilisateur"))) && (tpassword.getText().equals(cu.rs.getString("mdp"))) && ((ctype.getSelectedItem() + "").equals(cu.rs.getString("type_utilisateur")))) {
                    tr=true;
                    break;
                }
            }
            if ((tr == true) && (ctype.getSelectedItem().equals("Admin"))) {
                AcceuilAdmin aa=new AcceuilAdmin();
                aa.setVisible(true);
                this.setVisible(false);
            } else if ((tr == true) && (ctype.getSelectedItem().equals("Secrétaire"))) {
                AcceuilSecretaire as = new AcceuilSecretaire();
                as.setVisible(true);
                this.setVisible(false);
            } else if ((tr == true) && (ctype.getSelectedItem().equals("Médecin"))) {
                Médecin am=new Médecin();
                am.setVisible(true);
                this.setVisible(false);
            } else if ((tr == true) && (ctype.getSelectedItem().equals("Comptable"))) {
                AcceuilComptable ac=new AcceuilComptable();
                ac.setVisible(true);
                this.setVisible(false);
            } else {
                JOptionPane.showMessageDialog(this, "Username ou Password invalide veuillez réessayer", "ERREUR", JOptionPane.ERROR_MESSAGE);
            }
        } catch (SQLException ex) {
            Logger.getLogger(authentification.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_bconnecterActionPerformed

