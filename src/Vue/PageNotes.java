    public static void actualiser() {
        dft.setRowCount(0);
        dft.setColumnCount(0);
        try {
            dft.addColumn("Id");
            dft.addColumn("Contenu");

            ps = c.connexionBdd().prepareStatement("select * from Notes where medecin_id=?");
            ps.setString(1, authentification.tusername.getText());
            rs = ps.executeQuery();
            while (rs.next()) {
                dft.addRow(new Object[]{
                    rs.getString("note_id"),
                    rs.getString("contenue")
                }
                );
            }
            tnotes.setModel(dft);
        } catch (SQLException ex) {
            Logger.getLogger(PageNotes.class
                    .getName()).log(Level.SEVERE, null, ex);
        }
    }

