    private void bsupActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bsupActionPerformed
        if (Médecin.prv.charAt(29) == '1') {
            if (tnotes.getSelectedRowCount() == 1) {
                if (JOptionPane.showConfirmDialog(this, "Voulez vous vraiment supprimer la note ?", "confirmation", JOptionPane.YES_NO_OPTION) == JOptionPane.YES_OPTION) {
                    try {
                        ps = c.connexionBdd().prepareStatement("delete from notes where note_id=?");
                        ps.setString(1, tnotes.getValueAt(tnotes.getSelectedRow(), 0) + "");
                        ps.executeUpdate();
                        JOptionPane.showMessageDialog(this, "Suppression faite avec succés");
                        actualiser();
                    } catch (SQLException ex) {
                        Logger.getLogger(DetailsPatient.class.getName()).log(Level.SEVERE, null, ex);
                    }
                }
            }
        } else {
            JOptionPane.showMessageDialog(this, "Vous disposer pas de ce privilége !");
        }
    }//GEN-LAST:event_bsupActionPerformed

