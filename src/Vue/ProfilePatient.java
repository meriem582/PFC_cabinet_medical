    private void bajouterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bajouterActionPerformed
        if ( tnom.getText().isEmpty() || tprenom.getText().isEmpty()|| tnumsecurite.getText().isEmpty()
                || jdate.getDate() == null || tmaladie.getText().isEmpty()
                || ttel.getText().isEmpty() || ttelurgence.getText().isEmpty() || tadresse.getText().isEmpty() || tpath.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Veuillez Renseigner tout les champs !!");
        } else {
            try {
                tmatricule.setText(matricule());
                ps = c.connexionBdd().prepareStatement("insert into patient(matricule_pat,nom_pat,prénom_pat,date_naissance,maladie_pat,numTel,numTelUrgence,adresse_pat,antécédents_personnels,antécédents_familiaux,antécédents_médicaux,antécédents_chirurgicaux,groupe_sanguin,sexe,num_sécurité_social,photo_patient,email,note,situation_familiale,tpath) values(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)");
                ps.setString(1, tmatricule.getText());
                ps.setString(2, tnom.getText());
                ps.setString(3, tprenom.getText());
                SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
                String daten = sdf.format(jdate.getDate());
                ps.setString(4, daten);
                ps.setString(5, tmaladie.getText());
                ps.setString(6, ttel.getText());
                ps.setString(7, ttelurgence.getText());
                ps.setString(8, tadresse.getText());
                ps.setString(9, tantpersonnels.getText());
                ps.setString(10, tantfamiliaux.getText());
                ps.setString(11, tantmedicaux.getText());
                ps.setString(12, tantchirurgicaux.getText());
                ps.setString(13, csanguin.getSelectedItem() + "");
                ps.setString(14, csexe.getSelectedItem() + "");
                ps.setString(15, tnumsecurite.getText());
                try {
                    InputStream is = new FileInputStream(tpath.getText());
                    ps.setBlob(16, is);
                } catch (FileNotFoundException ex) {
                    Logger.getLogger(ProfilePatient.class.getName()).log(Level.SEVERE, null, ex);
                }
                ps.setString(17, temail.getText());
                ps.setString(18, tnote.getText());
                ps.setString(19, csituationfamiliale.getSelectedItem() + "");
                ps.setString(20, tpath.getText());
                ps.executeUpdate();
                JOptionPane.showMessageDialog(this, "le patient a été ajouter avec succés");
                AcceuilSecretaire.actualiser();
                dispose();
            } catch (SQLException ex) {
                Logger.getLogger(ProfilePatient.class.getName()).log(Level.SEVERE, null, ex);
            }
        }

    }//GEN-LAST:event_bajouterActionPerformed

